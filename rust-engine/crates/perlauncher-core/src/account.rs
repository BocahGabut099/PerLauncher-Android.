use serde::{Deserialize, Serialize};
use std::fmt;

#[derive(Clone, Copy, Debug, Eq, PartialEq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AccountProvider {
    Microsoft,
    ElyBy,
    Offline,
}

#[derive(Clone, Debug, Eq, PartialEq, Hash, Serialize, Deserialize)]
pub struct ProfileId {
    pub provider: AccountProvider,
    pub subject: String,
}

impl ProfileId {
    pub fn new(
        provider: AccountProvider,
        subject: impl Into<String>,
    ) -> Result<Self, ProfileError> {
        let subject = subject.into();
        if subject.trim().is_empty() || subject.len() > 256 {
            return Err(ProfileError::InvalidSubject);
        }
        Ok(Self { provider, subject })
    }
}

impl fmt::Display for ProfileId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{:?}:{}", self.provider, self.subject)
    }
}

/// Public metadata only. Tokens, passwords and OTP codes must never be stored here.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub struct PlayerProfile {
    pub id: ProfileId,
    pub player_name: String,
    pub game_uuid: Option<String>,
}

impl PlayerProfile {
    pub fn validate(&self) -> Result<(), ProfileError> {
        let name = self.player_name.trim();
        if name.is_empty()
            || name.len() > 16
            || !name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_')
        {
            return Err(ProfileError::InvalidPlayerName);
        }
        if self.id.provider == AccountProvider::Offline && self.game_uuid.is_some() {
            return Err(ProfileError::OfflineUuidMustBeEngineGenerated);
        }
        Ok(())
    }
}

#[derive(Debug, thiserror::Error, Eq, PartialEq)]
pub enum ProfileError {
    #[error("invalid profile subject")]
    InvalidSubject,
    #[error("invalid player name")]
    InvalidPlayerName,
    #[error("offline UUID must be generated by the selected engine")]
    OfflineUuidMustBeEngineGenerated,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn provider_is_part_of_profile_identity() {
        let ms = ProfileId::new(AccountProvider::Microsoft, "same-id").unwrap();
        let ely = ProfileId::new(AccountProvider::ElyBy, "same-id").unwrap();
        assert_ne!(ms, ely);
    }

    #[test]
    fn offline_profile_cannot_claim_a_provider_uuid() {
        let p = PlayerProfile {
            id: ProfileId::new(AccountProvider::Offline, "local-player").unwrap(),
            player_name: "LocalPlayer".into(),
            game_uuid: Some("forged".into()),
        };
        assert_eq!(
            p.validate(),
            Err(ProfileError::OfflineUuidMustBeEngineGenerated)
        );
    }
}
